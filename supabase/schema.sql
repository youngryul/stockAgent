CREATE TABLE IF NOT EXISTS alembic_version (
    version_num VARCHAR(32) NOT NULL,
    CONSTRAINT alembic_version_pkc PRIMARY KEY (version_num)
);

CREATE TABLE IF NOT EXISTS watchlist (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(32) NOT NULL,
    market VARCHAR(8) NOT NULL,
    name VARCHAR(128) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_watchlist_symbol UNIQUE (symbol)
);

CREATE TABLE IF NOT EXISTS analysis_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(16) NOT NULL,
    mode VARCHAR(16) NOT NULL DEFAULT 'watchlist',
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    error_message TEXT
);

CREATE TABLE IF NOT EXISTS signals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES analysis_runs (id),
    symbol VARCHAR(32) NOT NULL,
    market VARCHAR(8) NOT NULL,
    action VARCHAR(8) NOT NULL,
    horizon VARCHAR(8) NOT NULL DEFAULT 'SHORT',
    source VARCHAR(16) NOT NULL DEFAULT 'WATCHLIST',
    confidence DOUBLE PRECISION NOT NULL,
    entry_hint DOUBLE PRECISION,
    stop_loss DOUBLE PRECISION,
    take_profit DOUBLE PRECISION,
    holding_period_hint VARCHAR(64),
    rationale TEXT NOT NULL DEFAULT '',
    raw_json JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_signals_run_id ON signals (run_id);
CREATE INDEX IF NOT EXISTS ix_signals_symbol ON signals (symbol);
CREATE INDEX IF NOT EXISTS ix_signals_horizon ON signals (horizon);

CREATE TABLE IF NOT EXISTS portfolio_positions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    symbol VARCHAR(32) NOT NULL,
    market VARCHAR(8) NOT NULL,
    name VARCHAR(128) NOT NULL DEFAULT '',
