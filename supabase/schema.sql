    watching BOOLEAN NOT NULL DEFAULT true,
    study_progress DOUBLE PRECISION NOT NULL DEFAULT 0,
    overall_sentiment VARCHAR(16) NOT NULL DEFAULT 'NEUTRAL',
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0,
    last_studied_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_company_research UNIQUE (user_id, symbol)
);

CREATE TABLE IF NOT EXISTS research_conversations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    symbol VARCHAR(32) NOT NULL,
    title VARCHAR(256) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS research_messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id INTEGER NOT NULL REFERENCES research_conversations (id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    role VARCHAR(16) NOT NULL,
    content TEXT NOT NULL DEFAULT '',
    structured_json JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS research_notes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    symbol VARCHAR(32) NOT NULL,
    title VARCHAR(256) NOT NULL,
    summary TEXT NOT NULL DEFAULT '',
    new_learnings JSONB NOT NULL DEFAULT '[]'::jsonb,
    investment_idea TEXT NOT NULL DEFAULT '',
    things_to_check JSONB NOT NULL DEFAULT '[]'::jsonb,
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    related_thesis_id INTEGER,
    source_conversation_id INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS investment_theses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    symbol VARCHAR(32) NOT NULL,
    title VARCHAR(256) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    sentiment VARCHAR(16) NOT NULL DEFAULT 'NEUTRAL',
    confidence DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    evidence TEXT NOT NULL DEFAULT '',
    counter_evidence TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_reviewed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS thesis_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thesis_id INTEGER NOT NULL REFERENCES investment_theses (id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
    previous_status VARCHAR(16),
    new_status VARCHAR(16),
    previous_sentiment VARCHAR(16),
    new_sentiment VARCHAR(16),
    previous_confidence DOUBLE PRECISION,
    new_confidence DOUBLE PRECISION,
    reason TEXT NOT NULL DEFAULT '',
    source_type VARCHAR(32) NOT NULL DEFAULT 'USER',
    source_id INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

